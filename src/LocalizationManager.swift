/// Менеджер мультиязычности с поддержкой 11 языков (EN, UK, DE, FR, JA, ES, ZH-Hans, IT, PT, KO, RU),
/// автоопределения языка системы и мгновенного переключения интерфейса на лету.
public final class LocalizationManager {
    public static let shared = LocalizationManager()
    
    public enum Language: String, CaseIterable {
        case auto = "auto"
        case en = "en"
        case uk = "uk"
        case de = "de"
        case fr = "fr"
        case ja = "ja"
        case es = "es"
        case zhHans = "zh-Hans"
        case it = "it"
        case pt = "pt"
        case ko = "ko"
        case ru = "ru"
        
        public var flag: String {
            switch self {
            case .auto: return "🌐"
            case .en: return "🇺🇸"
            case .uk: return "🇺🇦"
            case .de: return "🇩🇪"
            case .fr: return "🇫🇷"
            case .ja: return "🇯🇵"
            case .es: return "🇪🇸"
            case .zhHans: return "🇨🇳"
            case .it: return "🇮🇹"
            case .pt: return "🇧🇷"
            case .ko: return "🇰🇷"
            case .ru: return "🇷🇺"
            }
        }
        
        public var identifier: String {
            return rawValue
        }
        
        public var nativeTitle: String {
            switch self {
            case .auto: return "Auto (System) / Авто"
            case .en: return "English"
            case .uk: return "Українська"
            case .de: return "Deutsch"
            case .fr: return "Français"
            case .ja: return "日本語"
            case .es: return "Español"
            case .zhHans: return "简体中文"
            case .it: return "Italiano"
            case .pt: return "Português"
            case .ko: return "한국어"
            case .ru: return "Русский"
            }
        }
        
        public var title: String {
            switch self {
            case .auto: return "\(flag) Auto (System)"
            default: return "\(flag) \(nativeTitle)"
            }
        }
    }
    
    private let userDefaultsKey = "selectedLanguage"
    private var currentLanguage: Language = .auto
    
    public init() {
        let saved = UserDefaults.standard.string(forKey: userDefaultsKey) ?? Language.auto.rawValue
        self.currentLanguage = Language(rawValue: saved) ?? .auto
    }
    
    public var selectedLanguage: Language {
        get { currentLanguage }
        set {
            currentLanguage = newValue
            UserDefaults.standard.set(newValue.rawValue, forKey: userDefaultsKey)
            NotificationCenter.default.post(name: .languageChanged, object: nil)
        }
    }
    
    /// Текущий активный языковой код с учетом автоопределения
    public var activeCode: String {
        switch currentLanguage {
        case .auto:
            for preferred in Locale.preferredLanguages {
                let lower = preferred.lowercased()
                if lower.hasPrefix("uk") { return "uk" }
                if lower.hasPrefix("ru") { return "ru" }
                if lower.hasPrefix("de") { return "de" }
                if lower.hasPrefix("fr") { return "fr" }
                if lower.hasPrefix("ja") { return "ja" }
                if lower.hasPrefix("es") { return "es" }
                if lower.hasPrefix("zh") { return "zh-Hans" }
                if lower.hasPrefix("it") { return "it" }
                if lower.hasPrefix("pt") { return "pt" }
                if lower.hasPrefix("ko") { return "ko" }
                if lower.hasPrefix("en") { return "en" }
            }
            return "en"
        default:
            return currentLanguage.rawValue
        }
    }
    
    public func tr(_ key: String) -> String {
        let lang = activeCode
        if let dict = strings[lang], let val = dict[key] {
            return val
        }
        // Fallback to English
        if let dict = strings["en"], let val = dict[key] {
            return val
        }
        return key
    }
    
